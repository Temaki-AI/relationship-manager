function hsl(hex: string) {
  const [r, g, b] = [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), delta = max - min, lightness = (max + min) / 2;
  const hue = !delta ? 0 : max === r ? ((g - b) / delta + (g < b ? 6 : 0)) * 60
    : max === g ? ((b - r) / delta + 2) * 60 : ((r - g) / delta + 4) * 60;
  const saturation = !delta ? 0 : delta / (1 - Math.abs(2 * lightness - 1));
  return `${Number(hue.toFixed(2))} ${Number((saturation * 100).toFixed(2))}% ${Number((lightness * 100).toFixed(2))}%`;
}

export function createThemeCss() {
  const values = Object.entries(semanticColors).map(([key, color]) => `    --${key}: ${hsl(color)};`);
  return `/* Generated by npm run design:tokens from packages/design/src/tokens.ts. */\n:root {\n${values.join('\n')}\n    --radius: ${radii.control / 16}rem;\n    --shadow-card: ${elevation.card};\n    --shadow-overlay: ${elevation.overlay};\n    --motion-fast: ${motion.fast}ms;\n    --motion-standard: ${motion.standard}ms;\n    --motion-enter: ${motion.enter}ms;\n}\n`;
}
