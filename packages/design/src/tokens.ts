/** Stable presentation color only; never an indicator of relationship health. */
export function avatarTone(name: string) {
  const hash = Array.from(name.normalize('NFC')).reduce((sum, char) => sum + char.codePointAt(0)!, 0);
  return avatarTones[hash % avatarTones.length];
}

